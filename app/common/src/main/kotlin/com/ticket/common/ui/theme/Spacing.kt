package com.ticket.common.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Sistema de espaciado basado en escala 4/8dp.
 * Mantiene consistencia visual en toda la aplicación.
 */
object TicketSpacing {
    /** Extra pequeño - 4dp: Espaciado entre iconos y texto */
    val xs = 4.dp

    /** Pequeño - 8dp: Espaciado interno de componentes */
    val sm = 8.dp

    /** Medio - 16dp: Espaciado estándar entre elementos */
    val md = 16.dp

    /** Grande - 24dp: Espaciado entre secciones */
    val lg = 24.dp

    /** Extra grande - 32dp: Espaciado entre grupos de secciones */
    val xl = 32.dp

    /** Extra extra grande - 48dp: Espaciado de pantalla completa */
    val xxl = 48.dp
}
